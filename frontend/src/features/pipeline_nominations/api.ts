import { apiRequest } from "@/services/api_client"

const BASE = "/api/v1/pipeline-nominations"

export type Region = "US" | "Non-US"
export type FacilityFilter = {
  name: string
  region: Region
  pipelines: string[]
}
export type FiltersResponse = {
  latest_date: string | null
  facilities: FacilityFilter[]
}

export type DailyPoint = { flow_date: string; bcf: number }
export type DailySeries = { name: string; points: DailyPoint[] }

export type CyclePoint = { gas_day: string; cycle: string; bcf: number }
export type CycleSeries = { name: string; points: CyclePoint[] }

export type ColumnMeta = {
  key: string
  group: string
  label: string
  partial: boolean
}
export type MatrixCell = {
  bcf: number | null
  change_pct: number | null
  // Cycle view: not published in this cycle, so the previous cycle's value is shown.
  carried: boolean
}
export type PipelineRow = { name: string; cells: MatrixCell[] }
export type FacilityRow = {
  name: string
  region: Region
  cells: MatrixCell[]
  pipelines: PipelineRow[]
}
export type RegionTotal = { region: Region; cells: MatrixCell[] }
export type MatrixTable = {
  columns: ColumnMeta[]
  // US facilities first, then the rest.
  facilities: FacilityRow[]
  // Only regions with a facility in the table.
  region_totals: RegionTotal[]
  total: MatrixCell[]
}

export type OverviewResponse = {
  latest_date: string | null
  daily_14: DailySeries[]
  daily_180: DailySeries[]
  monthly_table: MatrixTable
  daily_table: MatrixTable
  cycle_series: CycleSeries[]
  cycle_table: MatrixTable
}

export type AiOverviewResponse = {
  text: string
  model: string
  latest_date: string | null
  generated_at: string
}

// Backend pairs are "facility::pipeline", joined with "|".
export const selectionToken = (facility: string, pipeline: string) =>
  `${facility}::${pipeline}`

export function getFilters(): Promise<FiltersResponse> {
  return apiRequest<FiltersResponse>(`${BASE}/filters`)
}

/** An empty selection means all facilities and pipelines. */
export function getOverview(selected: string[]): Promise<OverviewResponse> {
  return apiRequest<OverviewResponse>(`${BASE}/overview`, {
    query: selected.length ? { selected: selected.join("|") } : {},
  })
}

/** A written summary of the current view, generated by the model. `refresh` skips the server cache. */
export function createAiOverview(
  selected: string[],
  refresh = false,
): Promise<AiOverviewResponse> {
  return apiRequest<AiOverviewResponse>(`${BASE}/ai-overview`, {
    method: "POST",
    query: {
      ...(selected.length ? { selected: selected.join("|") } : {}),
      ...(refresh ? { refresh: "true" } : {}),
    },
  })
}
