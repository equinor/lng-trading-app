from __future__ import annotations

from fastapi import APIRouter, Depends, HTTPException

from app.api.dependencies import require_reader
from app.features.pipeline_nominations.dependencies import PipelineNominationsServiceDep
from app.features.pipeline_nominations.schemas import (
    AiOverviewResponse,
    FiltersResponse,
    OverviewResponse,
    Source,
)
from app.features.pipeline_nominations.service import Selection

router = APIRouter(dependencies=[Depends(require_reader)])

# Pairs are "facility::pipeline", joined with "|" (names contain commas but not these).
_PAIR_SEPARATOR = "::"
_LIST_SEPARATOR = "|"


def _parse_selection(selected: str | None) -> Selection:
    pairs: Selection = set()
    for token in (selected or "").split(_LIST_SEPARATOR):
        facility, sep, pipeline = token.partition(_PAIR_SEPARATOR)
        if sep and facility.strip() and pipeline.strip():
            pairs.add((facility.strip(), pipeline.strip()))
    return pairs


@router.get("/filters", response_model=FiltersResponse)
def get_filters(service: PipelineNominationsServiceDep, source: Source = "woodmac"):
    """Facilities and their pipelines for one data source, for the filter tree."""
    return service.filters(source)


@router.get("/overview", response_model=OverviewResponse)
def get_overview(
    service: PipelineNominationsServiceDep,
    source: Source = "woodmac",
    selected: str | None = None,
):
    """Daily flow charts and the monthly and daily tables, optionally limited to selected facility::pipeline pairs."""
    return service.overview(source, _parse_selection(selected))


@router.post("/ai-overview", response_model=AiOverviewResponse)
def create_ai_overview(
    service: PipelineNominationsServiceDep,
    source: Source = "woodmac",
    selected: str | None = None,
    refresh: bool = False,
):
    """A written overview of the current view, generated by the model. POST because each call can cost a model request."""
    try:
        return service.ai_overview(source, _parse_selection(selected), refresh)
    except Exception as exc:
        raise HTTPException(
            status_code=502, detail="Could not generate the AI overview"
        ) from exc
